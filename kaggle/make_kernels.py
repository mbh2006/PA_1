def find_data_root():
    patterns = [
        "/kaggle/input/pacs-dataset01/pacs",
        "/kaggle/input/*/pacs",
        "/kaggle/input/*/*/pacs",
        "/kaggle/input/*/*/*/pacs",
    ]
    for pattern in patterns:
        for candidate in glob.glob(pattern):
            if all(os.path.isdir(os.path.join(candidate, d))
                   for d in ("photo", "art_painting", "cartoon", "sketch")):
                return candidate
    raise SystemExit("PACS dataset not found under /kaggle/input")


def clone_and_install():
    if not os.path.isdir(REPO_DIR):
        run(["git", "clone", REPO_URL, REPO_DIR])
    os.chdir(REPO_DIR)
    commit = subprocess.run(["git", "rev-parse", "HEAD"], capture_output=True,
                            text=True).stdout.strip()
    print("repo commit:", commit, flush=True)
    run([sys.executable, "-m", "pip", "install", "-q", "pyyaml", "scikit-learn", "tqdm"])
    return commit


def copy_baseline_results():
    if BASELINE_RUN and os.path.isdir(BASELINE_RESULTS_DATASET):
        destination = os.path.join("results", BASELINE_RUN)
        os.makedirs(destination, exist_ok=True)
        for filename in os.listdir(BASELINE_RESULTS_DATASET):
            shutil.copy2(os.path.join(BASELINE_RESULTS_DATASET, filename),
                         os.path.join(destination, filename))
        print("copied baseline results into", destination, flush=True)


def write_commit(commit):
    path = os.path.join("results", RUN_ID)
    if os.path.isdir(path):
        with open(os.path.join(path, "git_commit.txt"), "w") as fh:
            fh.write(commit + "\\n")


def zip_results():
    archive = shutil.make_archive("/kaggle/working/results_" + RUN_ID, "zip", "results", RUN_ID)
    print("archive:", archive, flush=True)
