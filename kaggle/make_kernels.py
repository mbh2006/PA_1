def dataset_sources(spec) -> list:
    sources = [PACS]
    if spec["kind"] in ("task2", "task3_eval") and spec["baseline"]:
        sources += [ERM_RESULTS, ERM_CKPT]
    if spec["kind"] == "task3":
        sources += [ERM_RESULTS]
    if spec["kind"] == "task3_eval":
        sources = [PACS, ERM_RESULTS, ERM_CKPT]
    if spec["kind"] == "task4_vanilla":
        sources = ["pankrzysiu/cifar10-python", "robsonricardodasilva/cifar-100-python"]
    if spec["kind"] == "task4_rest":
        sources = ["pankrzysiu/cifar10-python", "robsonricardodasilva/cifar-100-python",
                   f"{USER}/pa1-t4-vanilla-ckpt", f"{USER}/pa1-t4-vanilla-cache"]
    return sources


def render(spec) -> str:
    if spec["kind"] == "task3_eval":
        return TASK3_EVAL_ONLY
    if spec["kind"] == "task4_vanilla":
        return TASK4_HEADER.format(description="Task 4 vanilla training + cache",
                                   body=TASK4_VANILLA_BODY)
    if spec["kind"] == "task4_rest":
        return TASK4_HEADER.format(description="Task 4 GCSC + PROSER + OSR evaluation",
                                   body=TASK4_REST_BODY)
    header = COMMON_HEADER.format(description=f'{spec["kind"]} method {spec["config"]}',
                                  name=spec["name"], baseline=spec["baseline"])
    baseline_copy = "copy_baseline_results()" if spec["baseline"] else "pass"
    evaluations = TASK2_EVAL if spec["kind"] == "task2" else TASK3_EVAL
    train_module = "task2.train" if spec["kind"] == "task2" else "task3.train"
    body = TRAIN_COMMON.format(baseline_copy=baseline_copy, train_module=train_module,
                               config=spec["config"], extra_args=spec["extra"],
                               evaluations=evaluations)
    return header + body


def main() -> None:
    for spec in SPECS:
        folder = KERNELS_DIR / spec["name"]
        folder.mkdir(parents=True, exist_ok=True)
        (folder / "main.py").write_text(render(spec), encoding="utf-8")
        metadata = {
            "id": f"{USER}/{spec['slug']}",
            "title": spec["slug"].replace("-", " "),
            "code_file": "main.py",
            "language": "python",
            "kernel_type": "script",
            "is_private": True,
            "enable_gpu": True,
            "enable_internet": True,
            "dataset_sources": dataset_sources(spec),
            "competition_sources": [],
            "kernel_sources": [],
            "model_sources": [],
        }
        (folder / "kernel-metadata.json").write_text(json.dumps(metadata, indent=2), encoding="utf-8")
        print("generated", folder)


if __name__ == "__main__":
    main()
